// ---------------------------------------------------------------- services

function service(stack, svc) {
  const docs = [];
  const component = svc.template === 'web' ? 'frontend' : svc.template;
  const hasDb = svc.db.mode !== 'none';

  if (hasDb) {
    const role = toPgName(svc.name);
    docs.push({
      apiVersion: 'v1',
      kind: 'Secret',
      metadata: meta(stack, `${svc.name}-db`, 'database'),
      type: 'Opaque',
      stringData: {
        DATABASE_URL: `postgres://${role}:${DEV_PASSWORD(role)}@postgres:5432/${stack.postgres.database}`,
        DB_SCHEMA: svc.db.mode === 'own' ? role : 'public',
      },
    });
  }

  const env = {
    NODE_ENV: 'development',
    SERVICE_NAME: svc.name,
    ...(svc.node ? { PORT: svc.port, LOG_LEVEL: 'debug' } : { VITE_HMR_CLIENT_PORT: 80 }),
    ...(svc.node ? wiredEnv(stack, svc) : {}),
    ...svc.env,
  };
  const envFrom = hasDb ? [{ secretRef: { name: `${svc.name}-db` } }] : undefined;

  const probe = svc.node
    ? { httpGet: { path: '/healthz', port: 'http' } }
    : { tcpSocket: { port: 'http' } };
  const readiness = svc.node ? { httpGet: { path: '/readyz', port: 'http' } } : { tcpSocket: { port: 'http' } };

  const container = {
    name: svc.name,
    image: svc.image,
    imagePullPolicy: 'IfNotPresent',
    ports: [{ name: 'http', containerPort: svc.port }, ...(svc.node ? [{ name: 'debug', containerPort: 9229 }] : [])],
    env: envList(env),
    envFrom,
    readinessProbe: { ...readiness, periodSeconds: 5, failureThreshold: 3 },
    // Generous liveness: dev servers restart on file changes and must not be killed mid-reload.
    livenessProbe: { ...probe, initialDelaySeconds: 20, periodSeconds: 10, failureThreshold: 6 },
    resources: { requests: { cpu: '50m', memory: '128Mi' }, limits: { memory: '1Gi' } },
  };

  docs.push({
    apiVersion: 'apps/v1',
    kind: 'Deployment',
    metadata: meta(stack, svc.name, component),
    spec: {
      replicas: svc.replicas,
      selector: { matchLabels: { 'app.kubernetes.io/name': svc.name } },
      template: {
        metadata: { labels: labels(stack, svc.name, component) },
        spec: {
          // Migrations run before the app starts on every rollout (Knex's lock makes this safe with replicas).
          initContainers: hasDb
            ? [
                {
                  name: 'migrate',
                  image: svc.image,
                  imagePullPolicy: 'IfNotPresent',
                  command: ['npm', 'run', 'db:migrate', '-w', `apps/${svc.name}`],
                  env: envList({ NODE_ENV: 'development', SERVICE_NAME: svc.name }),
                  envFrom,
                },
              ]
            : undefined,
          terminationGracePeriodSeconds: 15,
          containers: [container],
        },
      },
    },
  });

  docs.push({
    apiVersion: 'v1',
    kind: 'Service',
    metadata: meta(stack, svc.name, component),
    spec: { selector: { 'app.kubernetes.io/name': svc.name }, ports: [{ name: 'http', port: svc.port, targetPort: 'http' }] },
  });

  if (svc.public) {
    const rules = Object.entries(svc.routes)
      .sort(([a], [b]) => b.length - a.length)
      .map(([prefix, target]) => ({
        matches: [{ path: { type: 'PathPrefix', value: prefix } }],
        backendRefs: [{ name: target, port: stack.services[target].port }],
      }));
    rules.push({ backendRefs: [{ name: svc.name, port: svc.port }] });
    docs.push(httpRoute(stack, svc.name, svc.public, rules));
  }
  return docs;
}

// ---------------------------------------------------------------- generated TypeScript

/** apps/<svc>/src/stack.gen.ts: env schema + typed clients derived from what the service uses/calls. */
export function stackGenTs(stack, svc) {
  const kit = new Set();
  const lines = [];
  const schemaParts = [];
  if (svc.db.mode !== 'none') {
    kit.add('dbEnvSchema');
    schemaParts.push('...dbEnvSchema.shape');
  }
  if (svc.uses.includes('redis')) {
    kit.add('redisEnvSchema');
    schemaParts.push('...redisEnvSchema.shape');
  }
  if (svc.uses.includes('rabbitmq')) {
    kit.add('rabbitmqEnvSchema');
    schemaParts.push('...rabbitmqEnvSchema.shape');
  }
  for (const target of svc.calls) schemaParts.push(`${toConst(target)}_URL: z.string().min(1)`);
  if (svc.calls.length) kit.add('createServiceClient').add('requireEnv');

  lines.push(
    '// GENERATED by `npm run stack:render` from stack.json. Do not edit by hand.',
    '// To change what this service uses or calls, edit stack.json (or use `npm run link` / `npm run addon`).',
  );
  if (kit.size) lines.push(`import { ${[...kit].sort().join(', ')} } from '@app/server-kit';`);
  lines.push(`import { z } from 'zod';`);
  for (const target of svc.calls) lines.push(`import { ${toCamel(target)}Routes } from '@app/contracts/${target}';`);
  lines.push(
    '',
    `export const stack = ${JSON.stringify({ service: svc.name, db: svc.db.mode, uses: svc.uses, calls: svc.calls })} as const;`,
    '',
    '/** Env vars wired in by stack.json (database, add-ons, called services). */',
    `export const stackEnvSchema = z.object({${schemaParts.length ? `\n  ${schemaParts.join(',\n  ')},\n` : ''}});`,
    '',
  );
  if (svc.calls.length) {
    lines.push(
      'function makeClients() {',
      '  return {',
      ...svc.calls.map((t) => `    ${toCamel(t)}: createServiceClient(${toCamel(t)}Routes, requireEnv('${toConst(t)}_URL')),`),
      '  };',
      '}',
      '',
      'let clients: ReturnType<typeof makeClients> | undefined;',
      '',
      '/** Typed clients for every service this one `calls` (request ids are propagated automatically). */',
      'export const serviceClients = () => (clients ??= makeClients());',
    );
  } else {
    lines.push('/** Typed clients for services this one `calls`. None yet — add with: npm run link <this> <other> */', 'export const serviceClients = () => ({});');
  }
  return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------- Tilt plan

function tiltPlan(stack) {
  const services = Object.values(stack.services).map((s) => ({
    name: s.name,
    image: s.image,
    template: s.template,
    node: s.node,
    debugPort: s.debugPort,
    migrate: s.db.mode !== 'none',
    deps: [...(s.db.mode !== 'none' ? ['db-provision'] : []), ...s.uses],
    links: s.public ? [`http://${s.public}`] : [],
  }));
  const addons = Object.entries(stack.addons)
    .filter(([, a]) => a.enabled)
    .map(([name]) => ({
      name,
      portForwards: name === 'redis' ? ['16379:6379'] : [],
      links: name === 'rabbitmq' ? ['http://rabbitmq.localhost'] : [],
    }));
  const routeNames = [
    ...Object.values(stack.services).filter((s) => s.public).map((s) => s.name),
    ...(stack.addons.rabbitmq.enabled ? ['rabbitmq'] : []),
  ];
  return {
    project: stack.project,
    namespace: stack.namespace,
    kubeContext: stack.kubeContext,
    postgresLocalPort: stack.postgres.localPort,
    services,
    addons,
    networkingObjects: [
      `gateway:gateway:${stack.namespace}`,
      ...routeNames.map((n) => `${n}:httproute:${stack.namespace}`),
    ],
    configObjects: [
      `${stack.namespace}:namespace`,
      `postgres-superuser:secret:${stack.namespace}`,
      `db-provision-sql:configmap:${stack.namespace}`,
      ...Object.values(stack.services)
        .filter((s) => s.db.mode !== 'none')
        .map((s) => `${s.name}-db:secret:${stack.namespace}`),
    ],
  };
}

