// Turn stack.json into Kubernetes manifests, per-service generated TS, and Tilt's resource plan.
// Output is deterministic: rendering twice yields identical files, so `render --check` can gate CI.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ADDONS, toCamel, toConst, toPgName, wiredEnv } from './stack.mjs';
import { toYamlDocs } from './yaml.mjs';

const HEADER = '# GENERATED by `npm run stack:render` from stack.json. Do not edit by hand.\n# Customize with patches in infra/k8s/patches/ (see README there).\n';
const DEV_PASSWORD = (role) => `${role}-dev-password`; // local cluster only

const labels = (stack, name, component) => ({
  'app.kubernetes.io/name': name,
  'app.kubernetes.io/part-of': stack.project,
  'app.kubernetes.io/component': component,
  'app.kubernetes.io/managed-by': 'stack-render',
});

const meta = (stack, name, component, extra = {}) => ({
  name,
  namespace: stack.namespace,
  labels: labels(stack, name, component),
  ...extra,
});

const envList = (obj) => Object.entries(obj).map(([name, value]) => ({ name, value: String(value) }));

// ---------------------------------------------------------------- core infra

function namespace(stack) {
  return [{ apiVersion: 'v1', kind: 'Namespace', metadata: { name: stack.namespace, labels: { 'app.kubernetes.io/part-of': stack.project } } }];
}

function postgres(stack) {
  const pg = stack.postgres;
  return [
    {
      apiVersion: 'v1',
      kind: 'Secret',
      metadata: meta(stack, 'postgres-superuser', 'database'),
      type: 'Opaque',
      stringData: { POSTGRES_USER: 'postgres', POSTGRES_PASSWORD: DEV_PASSWORD('postgres'), POSTGRES_DB: pg.database },
    },
    {
      apiVersion: 'v1',
      kind: 'Service',
      metadata: meta(stack, 'postgres', 'database'),
      spec: { selector: { 'app.kubernetes.io/name': 'postgres' }, ports: [{ name: 'postgres', port: 5432, targetPort: 5432 }] },
    },
    {
      apiVersion: 'apps/v1',
      kind: 'StatefulSet',
      metadata: meta(stack, 'postgres', 'database'),
      spec: {
        serviceName: 'postgres',
        replicas: 1,
        selector: { matchLabels: { 'app.kubernetes.io/name': 'postgres' } },
        template: {
          metadata: { labels: labels(stack, 'postgres', 'database') },
          spec: {
            containers: [
              {
                name: 'postgres',
                image: pg.image,
                ports: [{ name: 'postgres', containerPort: 5432 }],
                envFrom: [{ secretRef: { name: 'postgres-superuser' } }],
                env: [{ name: 'PGDATA', value: '/var/lib/postgresql/data/pgdata' }],
                readinessProbe: { exec: { command: ['pg_isready', '-U', 'postgres'] }, periodSeconds: 5 },
                resources: { requests: { cpu: '50m', memory: '128Mi' }, limits: { memory: '512Mi' } },
                volumeMounts: [{ name: 'data', mountPath: '/var/lib/postgresql/data' }],
              },
            ],
          },
        },
        volumeClaimTemplates: [
          {
            metadata: { name: 'data' },
            spec: { accessModes: ['ReadWriteOnce'], resources: { requests: { storage: pg.storage } } },
          },
        ],
      },
    },
  ];
}

/** Idempotent, declarative SQL: one role + schema per `own` service, shared group for `shared`, grants. */
export function provisionSql(stack) {
  const lines = ['-- GENERATED from stack.json. Re-run safely: every statement is idempotent.', '\\set ON_ERROR_STOP on', ''];
  const dbServices = Object.values(stack.services).filter((s) => s.db.mode !== 'none');
  const ownServices = dbServices.filter((s) => s.db.mode === 'own');
  const shared = dbServices.filter((s) => s.db.mode === 'shared');

  for (const s of dbServices) {
    const role = toPgName(s.name);
    lines.push(
      `-- ${s.name} (db: ${s.db.mode})`,
      `DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${role}') THEN CREATE ROLE "${role}" LOGIN; END IF; END $$;`,
      `ALTER ROLE "${role}" WITH LOGIN PASSWORD '${DEV_PASSWORD(role)}';`,
    );
    if (s.db.mode === 'own') {
      lines.push(
        `CREATE SCHEMA IF NOT EXISTS "${role}" AUTHORIZATION "${role}";`,
        `REVOKE ALL ON SCHEMA "${role}" FROM PUBLIC;`,
        `ALTER ROLE "${role}" SET search_path = "${role}";`,
      );
    } else {
      lines.push(`ALTER ROLE "${role}" SET search_path = public;`);
    }
    lines.push('');
  }

  if (shared.length) {
    lines.push(
      '-- shared: every `shared` service can use every table in public',
      `DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'shared_rw') THEN CREATE ROLE shared_rw NOLOGIN; END IF; END $$;`,
      'GRANT USAGE, CREATE ON SCHEMA public TO shared_rw;',
    );
    for (const s of shared) {
      const role = toPgName(s.name);
      lines.push(
        `GRANT shared_rw TO "${role}";`,
        `ALTER DEFAULT PRIVILEGES FOR ROLE "${role}" IN SCHEMA public GRANT ALL ON TABLES TO shared_rw;`,
        `ALTER DEFAULT PRIVILEGES FOR ROLE "${role}" IN SCHEMA public GRANT ALL ON SEQUENCES TO shared_rw;`,
      );
    }
    lines.push('GRANT ALL ON ALL TABLES IN SCHEMA public TO shared_rw;', 'GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO shared_rw;', '');
  }

  // Cross-service grants are fully declarative: revoke everything, then grant what stack.json says.
  const roles = dbServices.map((s) => toPgName(s.name));
  for (const owner of ownServices) {
    const schema = toPgName(owner.name);
    const others = roles.filter((r) => r !== schema);
    if (!others.length) continue;
    lines.push(`-- grants on schema "${schema}"`);
    for (const r of others) {
      lines.push(
        `REVOKE ALL ON ALL TABLES IN SCHEMA "${schema}" FROM "${r}";`,
        `REVOKE ALL ON ALL SEQUENCES IN SCHEMA "${schema}" FROM "${r}";`,
        `ALTER DEFAULT PRIVILEGES FOR ROLE "${schema}" IN SCHEMA "${schema}" REVOKE ALL ON TABLES FROM "${r}";`,
        `ALTER DEFAULT PRIVILEGES FOR ROLE "${schema}" IN SCHEMA "${schema}" REVOKE ALL ON SEQUENCES FROM "${r}";`,
        `REVOKE USAGE ON SCHEMA "${schema}" FROM "${r}";`,
      );
    }
    for (const [grantee, level] of Object.entries(owner.db.grants)) {
      const r = toPgName(grantee);
      const tablePrivs = level === 'readwrite' ? 'SELECT, INSERT, UPDATE, DELETE' : 'SELECT';
      lines.push(
        `GRANT USAGE ON SCHEMA "${schema}" TO "${r}";`,
        `GRANT ${tablePrivs} ON ALL TABLES IN SCHEMA "${schema}" TO "${r}";`,
        `ALTER DEFAULT PRIVILEGES FOR ROLE "${schema}" IN SCHEMA "${schema}" GRANT ${tablePrivs} ON TABLES TO "${r}";`,
      );
      if (level === 'readwrite') {
        lines.push(
          `GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA "${schema}" TO "${r}";`,
          `ALTER DEFAULT PRIVILEGES FOR ROLE "${schema}" IN SCHEMA "${schema}" GRANT USAGE, SELECT ON SEQUENCES TO "${r}";`,
        );
      }
    }
    lines.push('');
  }
  return lines.join('\n');
}

function dbProvision(stack) {
  const sql = provisionSql(stack);
  const checksum = createHash('sha256').update(sql).digest('hex').slice(0, 16);
  const pg = stack.postgres;
  return [
    { apiVersion: 'v1', kind: 'ConfigMap', metadata: meta(stack, 'db-provision-sql', 'database'), data: { 'provision.sql': sql } },
    {
      apiVersion: 'batch/v1',
      kind: 'Job',
      metadata: meta(stack, 'db-provision', 'database'),
      spec: {
        backoffLimit: 10,
        template: {
          // Changing the SQL changes this annotation, so Tilt recreates the Job and re-runs provisioning.
          metadata: { labels: labels(stack, 'db-provision', 'database'), annotations: { 'stack/sql-checksum': checksum } },
          spec: {
            restartPolicy: 'OnFailure',
            containers: [
              {
                name: 'psql',
                image: pg.image,
                command: [
                  'sh',
                  '-c',
                  `until pg_isready -h postgres -U postgres; do echo waiting for postgres; sleep 1; done; psql -h postgres -U postgres -d ${pg.database} -f /sql/provision.sql`,
                ],
                env: [{ name: 'PGPASSWORD', valueFrom: { secretKeyRef: { name: 'postgres-superuser', key: 'POSTGRES_PASSWORD' } } }],
                volumeMounts: [{ name: 'sql', mountPath: '/sql' }],
              },
            ],
            volumes: [{ name: 'sql', configMap: { name: 'db-provision-sql' } }],
          },
        },
      },
    },
  ];
}

function gateway(stack) {
  return [
    {
      apiVersion: 'gateway.networking.k8s.io/v1',
      kind: 'Gateway',
      metadata: meta(stack, 'gateway', 'networking'),
      spec: {
        gatewayClassName: stack.gateway.className,
        listeners: [{ name: 'http', protocol: 'HTTP', port: 80, allowedRoutes: { namespaces: { from: 'Same' } } }],
      },
    },
  ];
}

function httpRoute(stack, name, host, rules) {
  return {
    apiVersion: 'gateway.networking.k8s.io/v1',
    kind: 'HTTPRoute',
    metadata: meta(stack, name, 'networking'),
    spec: { parentRefs: [{ name: 'gateway' }], hostnames: [host], rules },
  };
}

