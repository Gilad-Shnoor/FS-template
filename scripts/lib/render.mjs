/** Compute every generated file as { relativePath: content }. Pure: no disk writes. */
export function renderAll(stack, root) {
  const files = {};
  const gen = 'infra/k8s/generated';
  const put = (rel, docs) => (files[`${gen}/${rel}`] = toYamlDocs(docs, HEADER));

  put('00-namespace.yaml', namespace(stack));
  put('10-postgres.yaml', postgres(stack));
  put('11-db-provision.yaml', dbProvision(stack));
  put('20-gateway.yaml', gateway(stack));
  for (const [name, addon] of Object.entries(stack.addons)) {
    if (addon.enabled) put(`30-addon-${name}.yaml`, ADDON_MANIFESTS[name](stack));
  }
  for (const svc of Object.values(stack.services)) put(`50-service-${svc.name}.yaml`, service(stack, svc));

  const patchDir = path.join(root, 'infra/k8s/patches');
  const patches = existsSync(patchDir)
    ? readdirSync(patchDir).filter((f) => /\.ya?ml$/.test(f)).sort()
    : [];
  const resources = Object.keys(files).map((f) => path.relative('infra/k8s', f)).sort();
  files['infra/k8s/kustomization.yaml'] = toYamlDocs(
    [
      {
        apiVersion: 'kustomize.config.k8s.io/v1beta1',
        kind: 'Kustomization',
        resources,
        patches: patches.length ? patches.map((p) => ({ path: `patches/${p}` })) : undefined,
      },
    ],
    HEADER,
  );

  files[`${gen}/tilt.json`] = JSON.stringify(tiltPlan(stack), null, 2) + '\n';

  for (const svc of Object.values(stack.services)) {
    if (svc.node && existsSync(path.join(root, 'apps', svc.name))) {
      files[`apps/${svc.name}/src/stack.gen.ts`] = stackGenTs(stack, svc);
    }
  }
  return files;
}

/**
 * Write generated files (only those that changed) and remove stale generated manifests.
 * With check=true nothing is written; returns the list of out-of-date paths.
 */
export function writeRendered(root, files, { check = false } = {}) {
  const changed = [];
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(root, rel);
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
    if (current === content) continue;
    changed.push(rel);
    if (!check) {
      mkdirSync(path.dirname(abs), { recursive: true });
      writeFileSync(abs, content);
    }
  }
  const genDir = path.join(root, 'infra/k8s/generated');
  if (existsSync(genDir)) {
    for (const f of readdirSync(genDir)) {
      const rel = `infra/k8s/generated/${f}`;
      if (files[rel]) continue;
      changed.push(`${rel} (stale)`);
      if (!check) rmSync(path.join(genDir, f));
    }
  }
  return changed;
}

